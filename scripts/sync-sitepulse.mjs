/* Copies the sitepulse scanner (the standalone open-source package, ../sitepulse) into lib/sitepulse/, so the
   /tools/site-check page and /api/site-check run exactly the code that is published, not a hand-made twin.

   Only the core is copied: no command line, no MCP server, no package entry point. The import paths are rewritten
   from "./x.js" (how the package writes them) to "./x" (how this app resolves them). Every copied file starts with a
   "generated" notice, so nobody edits the copy by mistake: change ../sitepulse and run this again.

   Usage: node scripts/sync-sitepulse.mjs [path-to-sitepulse]      (default ../sitepulse, or $SITEPULSE_DIR)
   Add --check to only report whether lib/sitepulse is up to date (exit 1 if not), for a CI step. */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const root = path.resolve(args.find((a) => !a.startsWith("--")) ?? process.env.SITEPULSE_DIR ?? "../sitepulse");
const src = path.join(root, "src");
const out = path.resolve("lib/sitepulse");

if (!existsSync(src)) {
  console.error(`sync-sitepulse: no sources at ${src}. Pass the path to the sitepulse folder.`);
  process.exit(2);
}

const NOT_COPIED = new Set(["cli.ts", "mcp.ts", "index.ts"]);
const files = [];
const walk = (dir, rel = "") => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) walk(path.join(dir, e.name), r);
    else if (e.name.endsWith(".ts") && !NOT_COPIED.has(r)) files.push(r);
  }
};
walk(src);
files.sort();

let version = "unknown";
let commit = "unknown";
try {
  version = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8")).version;
  commit = execFileSync("git", ["-C", root, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
} catch { /* the notice just says unknown */ }

const header = `/* GENERATED by scripts/sync-sitepulse.mjs from the sitepulse package ${version} (commit ${commit}). Do not edit here:
   change the package and run the script again. */\n\n`;

const build = (rel) => header + readFileSync(path.join(src, rel), "utf8").replace(/\r\n/g, "\n").replace(/(from\s+["'])(\.{1,2}\/[^"']+?)\.js(["'])/g, "$1$2$3");

const wanted = new Map(files.map((f) => [f, build(f)]));

if (checkOnly) {
  let stale = 0;
  for (const [f, text] of wanted) {
    const p = path.join(out, f);
    if (!existsSync(p) || readFileSync(p, "utf8").replace(/\r\n/g, "\n") !== text) { console.error(`out of date: lib/sitepulse/${f}`); stale++; }
  }
  if (stale) process.exit(1);
  console.log(`lib/sitepulse is up to date (sitepulse ${version}, ${commit}).`);
} else {
  rmSync(out, { recursive: true, force: true });
  for (const [f, text] of wanted) {
    const p = path.join(out, f);
    mkdirSync(path.dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
  console.log(`Copied ${files.length} files from sitepulse ${version} (${commit}) into lib/sitepulse/.`);
}
